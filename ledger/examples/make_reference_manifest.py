"""Rebuild `ledger/examples/reference-submission.json`, the sample manifest for the reference
submission (the package's `sample_submission/`).

    uv run python ledger/examples/make_reference_manifest.py \
        /home/cld-main/work/vqcc-data/google-verifiable-quantum-circuit-compilation /tmp/reference.zip

It builds the reference zip deterministically (outside git), hashes every file, and folds in the
verifier runs captured in `ledger/examples/reference/logs/` (invsqrt and dfthcsos, full default
shots, local salt below). dqi was not run here (≈ 6 GB RAM per worker; P0-4 owns the full
reference calibration), so its record is marked `measured: false` and carries the reference
figures from arXiv:2610.23832v2 §III.2.2 and the PRA-171 zero-failure arithmetic.

The reference circuits are Google's (Apache-2.0, `verifiers/LICENSE.txt`), not generated by
Praxen code, so this manifest can never pass G5 as it stands: R10 requires our own generator.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from ledger.archive import build_zip  # noqa: E402
from ledger.evidence import collect_verifier_evidence, load_summary  # noqa: E402
from ledger.gates.runner import start_candidate  # noqa: E402
from ledger.run_manifest import (  # noqa: E402
    Provenance,
    kickmix_build_id,
    sha256_file,
    write_manifest,
)

HERE = Path(__file__).resolve().parent
LOGS = HERE / "reference" / "logs"
SALT = "PRA171_LOCAL_PUBLIC_FIXED_SALT_0001"
DATA_URL = "https://www.kaggle.com/competitions/google-verifiable-quantum-circuit-compilation/data"
QUALTRAN_STARTER_PIN = "c58703d00b01c346d3e77d3913cf2d6e9e556be3"
VERIFIERS = {
    "invsqrt": "verifiers/invsqrt/verify_submission_invsqrt.py",
    "dqi": "verifiers/dqi/verify_submission_dqi.py",
    "dfthcsos": "verifiers/dfthcsos/verify.py",
}
# dqi reference figures (not measured here): Q and mean Toffolis from arXiv:2610.23832v2
# §III.2.2; eps_plus and cost from the PRA-171 zero-failure calculation at N = 102,400 and
# delta = 2^-128.
DQI_REFERENCE = {
    "num_qubits": 1893,
    "toffoli_count": 5725461.0,
    "eps_plus": 0.0008660587301657926,
    "repetition_factor": 1.1912604648115832,
    "cost": 24440968846372.203,
}


def main(data: Path, zip_path: Path) -> Path:
    build_zip(data / "sample_submission", zip_path)
    provenance = Provenance(
        licence="Apache-2.0",
        parent_url=DATA_URL,
        notes="Google's reference circuit from the competition package sample_submission/ "
              "(verifiers/LICENSE.txt, Apache-2.0). Not generated by Praxen code.",
    )
    manifest = start_candidate(
        zip_path, "reference", {t: provenance for t in VERIFIERS}, salt_label=SALT,
        notes="Sample manifest for the reference submission (PRA-175). invsqrt and dfthcsos are "
              "measured verifier runs; dqi is reference-document figures (measured: false). "
              "Cannot pass G5: no Praxen generator (R10).",
    )
    manifest.generator_commit = "none: package sample_submission, not generated by Praxen code"
    manifest.kickmix_build_id = kickmix_build_id(data / "kickmix" / "kickmix.so")
    manifest.qualtran_pin = QUALTRAN_STARTER_PIN
    verifier_hashes = {t: sha256_file(data / p) for t, p in VERIFIERS.items()}
    summaries = {t: load_summary(LOGS / f"{t}.json") for t in ("invsqrt", "dfthcsos")}
    collect_verifier_evidence(
        manifest,
        "reference-baseline",
        summaries,
        logs=sorted(LOGS.iterdir()),
        log_root=HERE,
        verifier_hashes=verifier_hashes,
        # The reference is its own baseline under the same salt, so its ratio is 1 by definition.
        baseline_costs={t: s["score"] for t, s in summaries.items()},
        commands=[
            (f'PYTHONPATH="$DATA/kickmix:$DATA/verifiers" python -B "$DATA/{VERIFIERS["invsqrt"]}" '
             f'"$DATA/sample_submission/invsqrt.kmb" --salt {SALT} --max-workers 8'),
            (f'PYTHONPATH="$DATA/kickmix:$DATA/verifiers" python -B "$DATA/{VERIFIERS["dfthcsos"]}" '
             f'"$DATA/sample_submission/dfthcsos" --salt {SALT}'),
        ],
        notes="Run with CPython 3.13.13 and the shipped kickmix.so, numpy and scipy in an "
              "ephemeral uv environment, full default shots. dqi not run.",
        root=HERE / "reference" / "evidence",
    )
    dqi = manifest.tasks["dqi"]
    dqi.verifier_sha256 = verifier_hashes["dqi"]
    dqi.num_qubits = DQI_REFERENCE["num_qubits"]
    dqi.toffoli_count = DQI_REFERENCE["toffoli_count"]
    dqi.shots = 102400
    dqi.eps_plus = DQI_REFERENCE["eps_plus"]
    dqi.cost = DQI_REFERENCE["cost"]
    dqi.baseline_cost = DQI_REFERENCE["cost"]
    dqi.metrics = {
        "repetition_factor": DQI_REFERENCE["repetition_factor"],
        "source": "arXiv:2610.23832v2 §III.2.2 (Q, Toffolis); PRA-171 inventory §5 "
                  "(eps_plus, R, cost at zero failures). Not a verifier run.",
    }
    return write_manifest(manifest, HERE / "reference-submission.json")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    print(main(Path(sys.argv[1]), Path(sys.argv[2])))
