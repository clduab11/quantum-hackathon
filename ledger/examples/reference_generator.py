def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def generate(task: str, out: Path, data: Path = DATA) -> dict[str, str]:
    """Copy `task`'s pinned reference files into `out`; raise if any hash differs."""
    written = {}
    for rel, pin in PINS[task].items():
        src = data / "sample_submission" / rel
        actual = _sha256(src)
        if actual != pin:
            raise SystemExit(f"{src}: SHA-256 {actual} does not match pin {pin}")
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        written[rel] = actual
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--task", choices=sorted(PINS), required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--data", type=Path, default=DATA)
    args = parser.parse_args()
    for rel, digest in generate(args.task, args.out, args.data).items():
        print(f"{digest}  {rel}")


if __name__ == "__main__":
    main()
