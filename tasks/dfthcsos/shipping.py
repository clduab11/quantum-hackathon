"""Build the PRA-247 ANGLE family from the declared Gluzdov v8 factor.

The input root is VQCC_DATA (G5 supplies an isolated staging directory).
There is no reference-factor fallback. The factor bytes and 11-bit words
are preserved; all circuits are regenerated by our committed ANF builder.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from tasks.dfthcsos.circuit import generate as build_family
from tasks.dfthcsos.generate import DEFAULT_DATA, sha256_file

INPUT_PATH = Path('inputs/thc/femoco_thc_r5.npz')
INPUT_SHA256 = '809a992900937425f01a0593803921873f7bb472d590592c378d3ceb23657df5'


def generate(out: Path, *, data: Path = DEFAULT_DATA, batch_size: int):
    source = Path(data) / INPUT_PATH
    if sha256_file(source) != INPUT_SHA256:
        raise ValueError('declared Gluzdov v8 factor SHA-256 mismatch')
    return build_family(out, factorization=source, source_brot=11, brot=11,
                        batch_size=batch_size, bank_bits=0, scratch=8, pebble_degree=4)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--data', type=Path, default=DEFAULT_DATA)
    parser.add_argument('--batch-size', type=int, required=True)
    args = parser.parse_args()
    print(json.dumps(generate(args.out, data=args.data, batch_size=args.batch_size), indent=2))


if __name__ == '__main__':
    main()
